"""Render the top profile card (github-profile.svg).

The card holds no live data, so it is generated by hand rather than by the
daily workflow: edit the values below, run `python generate_profile.py`,
then commit the SVG.
"""
import base64
import re

import requests

# Purple on near-black. Change these values to retheme the card.
PALETTE = {
    'ground': '#0a0910',   # card background (almost black)
    'text': '#ece8ff',     # name
    'muted': '#958db3',    # greeting, bio, labels
    'accent': '#a78bfa',   # username, corner mark, label tick
    'glow': '#6d28d9',     # glow behind the corner, bottom of the side bar
    'spark': '#f0abfc',    # top of the side bar
    'line': '#a78bfa',     # card border
    'edgeAlpha': '0.30',
}

MONO = "'SF Mono','SFMono-Regular','Cascadia Mono','Segoe UI Mono','Roboto Mono','DejaVu Sans Mono',monospace"

USERNAME = 'nyarq'
GREETING = 'Hi there! 👋'
BIO = 'Python을 주력으로 AI 관련 프로그램들을 만들고 있습니다.'

# skillicons.dev ids, one row. SQL has no generic icon there, so MySQL stands in.
SKILLS = ['python', 'cs', 'mysql', 'js', 'html', 'css', 'cloudflare']

# Tools skillicons.dev does not carry. Each is drawn from its Simple Icons logo
# on the same dark rounded tile, as (simpleicons slug, logo colour).
EXTRA_ICONS = [('dbeaver', '#ece8ff')]
TILE_FILL = '#242938'  # skillicons.dev dark tile colour

SANS = "'Segoe UI','Pretendard','Apple SD Gothic Neo','Noto Sans KR',Helvetica,Arial,sans-serif"

WIDTH = 840
HEIGHT = 330
ICON_HEIGHT = 52
PATH = 'github-profile.svg'


def escape(text):
    return (str(text).replace('&', '&amp;').replace('<', '&lt;')
            .replace('>', '&gt;').replace('"', '&quot;'))


def fetchSkillIcons():
    """Fetch the icon strip once and inline it, since an SVG shown through <img>
    cannot load external images on its own."""
    resp = requests.get(
        'https://skillicons.dev/icons',
        params={'i': ','.join(SKILLS), 'theme': 'dark'},
        timeout=30,
    )
    resp.raise_for_status()
    encoded = base64.b64encode(resp.content).decode('ascii')
    # Each icon is 256 units wide with a 44 unit gap between icons.
    units = len(SKILLS) * 300 - 44
    return f'data:image/svg+xml;base64,{encoded}', ICON_HEIGHT * units / 256


def fetchExtraTiles(startX, y):
    """Draw each Simple Icons logo on a tile matching the skillicons.dev strip."""
    scale = ICON_HEIGHT / 256
    tiles = []
    x = startX
    for slug, colour in EXTRA_ICONS:
        resp = requests.get(f'https://cdn.simpleicons.org/{slug}', timeout=30)
        resp.raise_for_status()
        pathData = re.search(r'<path[^>]*\sd="([^"]+)"', resp.text).group(1)
        # The logo sits on a 24 unit grid; 160 of the tile's 256 units leaves the
        # same margin the skillicons.dev logos have.
        tiles.append(
            f'  <g transform="translate({x:.1f},{y}) scale({scale:.5f})">\n'
            f'    <rect width="256" height="256" rx="60" fill="{TILE_FILL}"/>\n'
            f'    <g transform="translate(48,48) scale({160 / 24:.5f})">\n'
            f'      <path d="{pathData}" fill="{colour}"/>\n'
            f'    </g>\n'
            f'  </g>'
        )
        x += 300 * scale
    return '\n'.join(tiles)


def generateProfileSvg(path):
    p = PALETTE
    iconHref, iconWidth = fetchSkillIcons()
    # Continue the strip with the same 44 unit gap the skillicons.dev icons use.
    extraTiles = fetchExtraTiles(56 + iconWidth + 44 * ICON_HEIGHT / 256, 248)

    svg = f'''<svg width="{WIDTH}" height="{HEIGHT}" viewBox="0 0 {WIDTH} {HEIGHT}" fill="none" xmlns="http://www.w3.org/2000/svg" role="img" aria-label="Hi, I'm {USERNAME}">
  <defs>
    <clipPath id="pc-card">
      <rect width="{WIDTH}" height="{HEIGHT}" rx="10"/>
    </clipPath>
    <pattern id="pc-dots" width="22" height="22" patternUnits="userSpaceOnUse">
      <circle cx="1" cy="1" r="1" fill="{p["text"]}" fill-opacity="0.05"/>
    </pattern>
    <linearGradient id="pc-bar" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0%" stop-color="{p["spark"]}"/>
      <stop offset="50%" stop-color="{p["accent"]}"/>
      <stop offset="100%" stop-color="{p["glow"]}"/>
    </linearGradient>
    <radialGradient id="pc-glow" cx="50%" cy="50%" r="50%">
      <stop offset="0%" stop-color="{p["glow"]}" stop-opacity="0.22"/>
      <stop offset="100%" stop-color="{p["glow"]}" stop-opacity="0"/>
    </radialGradient>
  </defs>

  <g clip-path="url(#pc-card)">
    <rect width="{WIDTH}" height="{HEIGHT}" fill="{p["ground"]}"/>
    <rect width="{WIDTH}" height="{HEIGHT}" fill="url(#pc-dots)"/>
    <ellipse cx="{WIDTH - 120}" cy="70" rx="260" ry="190" fill="url(#pc-glow)"/>
    <rect width="5" height="{HEIGHT}" fill="url(#pc-bar)"/>
  </g>

  <path d="M{WIDTH - 46} 22 H{WIDTH - 22} V46" stroke="{p["accent"]}" stroke-opacity="0.55" stroke-width="1.5"/>

  <text x="56" y="76" font-family="{SANS}" font-size="20" fill="{p["muted"]}">{escape(GREETING)}</text>
  <text x="54" y="138" font-family="{SANS}" font-size="56" font-weight="700" fill="{p["text"]}">I'm <tspan fill="{p["accent"]}">{escape(USERNAME)}</tspan></text>
  <text x="56" y="184" font-family="{SANS}" font-size="17" fill="{p["muted"]}">{escape(BIO)}</text>

  <rect x="56" y="222" width="3" height="12" rx="1" fill="{p["accent"]}"/>
  <text x="66" y="232" font-family="{MONO}" font-size="11.5" font-weight="600" letter-spacing="1.6" fill="{p["muted"]}">SKILLS</text>
  <image x="56" y="248" width="{iconWidth:.1f}" height="{ICON_HEIGHT}" href="{iconHref}"/>
{extraTiles}

  <rect x="0.5" y="0.5" width="{WIDTH - 1}" height="{HEIGHT - 1}" rx="10" stroke="{p["line"]}" stroke-opacity="{p["edgeAlpha"]}"/>
</svg>'''

    with open(path, 'w', encoding='utf-8') as f:
        f.write(svg)
    print(f'Generated {path}')


if __name__ == '__main__':
    generateProfileSvg(PATH)
